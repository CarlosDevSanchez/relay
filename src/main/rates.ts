import { chmodSync, mkdirSync, readFileSync, renameSync, statSync, watch, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Account, AccountUsage, UsageWindow } from '../shared/types'
import { liveWindows, warnText } from '../shared/usage'
import { scanCodexRates } from './codex'
import { loadCopies } from './store'

/**
 * Official usage for Claude (https://code.claude.com/docs/en/statusline): the CLI runs the configured `statusLine.command` with a JSON on stdin that
 * carries `rate_limits.five_hour|seven_day.{used_percentage, resets_at (epoch s)}` (Pro/Max, after the first API response; each window may be absent
 * and is dropped once its reset passes). Relay passes its own script through the official `--settings` flag; the script saves that JSON for main.
 */

export const statusDir = (home: string): string => join(home, 'status')
export const statusScriptPath = (home: string): string => join(home, 'bin', 'statusline.sh')

/** POSIX sh. Saves the CLI's JSON (atomically) to $RELAY_STATUS_FILE, then chains the user's own status line, or prints `5h 48% · 7d 31%`. No other side effect. */
export const STATUS_SCRIPT = `#!/bin/sh
# Relay status line (generated by Relay at startup; edits are overwritten).
umask 077
json=$(cat)
if [ -n "$RELAY_STATUS_FILE" ]; then
  tmp="$RELAY_STATUS_FILE.$$.tmp"
  printf '%s' "$json" > "$tmp" && mv "$tmp" "$RELAY_STATUS_FILE"
fi
if [ -n "$RELAY_USER_STATUSLINE" ]; then
  printf '%s' "$json" | sh -c "$RELAY_USER_STATUSLINE"
else
  flat=$(printf '%s' "$json" | tr -d ' \\n\\r\\t')
  out=
  for w in five_hour:5h seven_day:7d; do
    p=$(printf '%s' "$flat" | sed -n "s/.*\\"\${w%%:*}\\":{[^}]*\\"used_percentage\\":\\([0-9.]*\\).*/\\1/p")
    [ -n "$p" ] && out="\${out:+$out · }\${w##*:} \${p%%.*}%"
  done
  [ -n "$out" ] && printf '%s' "$out"
fi
exit 0
`

/** Writes the script (0755) and the private status dir. Returns the script path. */
export function writeStatusScript(home: string): string {
  const file = statusScriptPath(home)
  mkdirSync(join(home, 'bin'), { recursive: true })
  mkdirSync(statusDir(home), { recursive: true, mode: 0o700 })
  writeFileSync(`${file}.tmp`, STATUS_SCRIPT, { mode: 0o755 })
  chmodSync(`${file}.tmp`, 0o755)
  renameSync(`${file}.tmp`, file)
  return file
}

const shq = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`

/** Inline JSON for `claude --settings` (`--settings <file-or-json>` in `claude --help`). */
export const claudeSettingsArgs = (script: string): string[] => ['--settings', JSON.stringify({ statusLine: { type: 'command', command: shq(script) } })]

/** The user's own `statusLine.command` (read-only; absent / invalid / not a command = undefined) so Relay's script can chain it. */
export function readUserStatusLine(configDir: string): string | undefined {
  try {
    const s = JSON.parse(readFileSync(join(configDir, 'settings.json'), 'utf8'))?.statusLine
    return s?.type === 'command' && typeof s.command === 'string' && s.command.trim() ? s.command : undefined
  } catch {
    return undefined
  }
}

/** Env for a Claude session pty: where to save the JSON and which user status line to chain. */
export const statusEnv = (home: string, a: Account): Record<string, string> => {
  const user = readUserStatusLine(a.configDir)
  return { RELAY_STATUS_FILE: join(statusDir(home), `${a.id}.json`), ...(user ? { RELAY_USER_STATUSLINE: user } : {}) }
}

const pct = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v)

/** Defensive parse of the status line JSON: only the rate-limit windows and the session id are read. */
export function parseStatusJson(text: string): { sessionId?: string; windows: UsageWindow[] } | undefined {
  let d: any
  try {
    d = JSON.parse(text)
  } catch {
    return undefined
  }
  if (!d || typeof d !== 'object') return undefined
  const windows: UsageWindow[] = []
  for (const [key, id] of [['five_hour', '5h'], ['seven_day', '7d']] as const) {
    const w = d.rate_limits?.[key]
    if (pct(w?.used_percentage) && pct(w.resets_at)) windows.push({ id, pct: Math.min(100, Math.max(0, w.used_percentage)), resetsAt: w.resets_at * 1000 })
  }
  return { ...(typeof d.session_id === 'string' && d.session_id.length <= 100 ? { sessionId: d.session_id } : {}), windows }
}

export interface TrackerDeps {
  accounts(): Account[]
  warnAt(): number
  emit(u: AccountUsage): void
  /** a window crossed warnAt: composed text + account */
  warn(a: Account, text: string): void
  now?(): number
}

/**
 * Last-known official usage per account. Claude: `<home>/status/<accountId>.json` (fs.watch + a slow rescan); Codex: newest `rate_limits` of its rollouts (polled).
 * One warning per window (account + window + reset time); what is already above the threshold at startup is not announced.
 */
export function trackUsage(home: string, deps: TrackerDeps): { get(): AccountUsage[]; scan(codex?: boolean): void; stop(): void } {
  const now = deps.now ?? Date.now
  const dir = statusDir(home)
  const last = new Map<string, AccountUsage>()
  const seenMtime = new Map<string, number>()
  const warned = new Set<string>()
  let seeding = true

  const publish = (a: Account, windows: UsageWindow[], updatedAt: number): void => {
    const prev = last.get(a.id)
    if (prev && prev.updatedAt === updatedAt && JSON.stringify(prev.windows) === JSON.stringify(windows)) return
    const u: AccountUsage = { accountId: a.id, windows, updatedAt }
    last.set(a.id, u)
    for (const w of liveWindows(windows, now())) {
      const key = `${a.id}|${w.id}|${w.resetsAt}`
      if (w.pct < deps.warnAt() || warned.has(key)) continue
      warned.add(key)
      if (!seeding) deps.warn(a, warnText(a.label, w, now()))
    }
    deps.emit(u)
  }

  const scan = (codex = false): void => {
    for (const a of deps.accounts()) {
      if (a.provider === 'codex') {
        if (!codex) continue
        const r = scanCodexRates(a.configDir, now(), loadCopies(home)[a.id])
        if (r) publish(a, r.windows, r.ts)
        continue
      }
      const file = join(dir, `${a.id}.json`)
      try {
        const st = statSync(file)
        if (st.size > 1_000_000 || seenMtime.get(a.id) === st.mtimeMs) continue
        seenMtime.set(a.id, st.mtimeMs)
        const p = parseStatusJson(readFileSync(file, 'utf8'))
        if (p) publish(a, p.windows, st.mtimeMs)
      } catch {
        // no file yet / vanished mid-write
      }
    }
  }

  scan(true)
  seeding = false
  let n = 0
  const timer = setInterval(() => scan(++n % 6 === 0), 5000) // fs.watch can miss events (network / some FS): slow rescan; Codex is only polled
  timer.unref()
  let w: ReturnType<typeof watch> | undefined
  try {
    mkdirSync(dir, { recursive: true, mode: 0o700 })
    w = watch(dir, () => scan())
    w.on('error', () => undefined)
  } catch {
    // the rescan covers it
  }
  return {
    get: () => [...last.values()].map((u) => ({ ...u, windows: liveWindows(u.windows, now()) })).filter((u) => u.windows.length),
    scan,
    stop: () => (clearInterval(timer), w?.close())
  }
}
